/** Human-readable Markdown rendering of a Launch Blueprint. The JSON is authoritative; this is for reading. */
import type { ClaimRef, LaunchBlueprint, Price } from "./types.ts";

const money = (p: Price) => (p.value == null ? "UNKNOWN" : `$${p.value % 1 ? p.value.toFixed(2) : p.value}`) + ` (${p.evidence})`;
const cite = (c: ClaimRef) => `${c.statement} _[${c.evidence}, ${c.claim_id}]_`;
const esc = (s: string) => s.replace(/\|/g, "\\|");
const list = (xs: string[]) => (xs.length ? xs.map((x) => `- ${x}`).join("\n") : "- _none_");

export function renderMarkdown(bp: LaunchBlueprint): string {
  const L: string[] = [];
  L.push(`# ${bp.display_name} Launch Blueprint v${bp.version}`, "");
  L.push(`**Status:** ${bp.status} · **Implementation:** ${bp.implementation_status} · **Kind:** ${bp.business_kind.replace("_", " ")} · **Created:** ${bp.created_at}`);
  L.push(`**Source brief:** ${bp.source_brief.brief_id} v${bp.source_brief.version} (${bp.source_brief.status}), \`${bp.source_brief.content_hash.slice(0, 19)}…\``);
  L.push(`**Generated by:** ${bp.generated_by.tool} ${bp.generated_by.tool_version} (deterministic) · **Auto-launch:** never`, "");
  L.push("> A blueprint is a plan. Nothing in it is built, tested or live until a build stage records independent gate receipts. Launch always needs the owner's explicit approval.", "");

  L.push("## Decision from the brief", "", `**${bp.go_hold.call.replace(/_/g, " ")}**${bp.go_hold.subject ? `: ${bp.go_hold.subject}` : ""}. ${bp.go_hold.rationale}`, "", `Falsifying test: ${bp.go_hold.falsifying_test}`, "");

  L.push("## Positioning", "", bp.positioning.one_line, "");
  L.push("| Segment | Priority |", "|---|---|", ...bp.positioning.segments.map((s) => `| ${esc(s.name)}${s.id === bp.positioning.primary_segment_id ? " (target)" : ""} | ${s.priority} |`), "");

  L.push("## Offer ladder", "", "| Tier | Item | Price | Playbook |", "|---|---|---|---|");
  for (const t of bp.offer_ladder) L.push(`| ${t.tier} | ${esc(t.item)} | ${money(t.price)} | ${t.playbook} |`);
  L.push("");

  L.push("## Products", "");
  for (const p of bp.products) {
    L.push(`### ${p.name} (\`${p.product_id}\`)`, "");
    L.push(`${p.tier} tier · ${money(p.price)} · playbook \`${p.playbook}\` · ${p.status}${p.registry_product_id ? ` · builds on registry \`${p.registry_product_id}\`` : ""}`, "");
    L.push(`Format: ${p.format}`, "");
    if (p.must_include.length) L.push("Must include:", list(p.must_include), "");
    if (p.must_not.length) L.push("Must not:", list(p.must_not), "");
    L.push("Deliverables:", list(p.deliverables.map((d) => `**${d.kind}** (${d.file_format}): ${d.spec}`)), "");
    L.push(`Gates: ${p.gates.join(", ")}`, "");
    if (p.falsifying_test) L.push(`Falsifying test: ${p.falsifying_test}`, "");
  }

  const sf = bp.sales_framework;
  L.push("## Sales framework (Promise, Pain, Proof, Plan, Picture)", "");
  L.push(`**Promise (draft):** ${sf.promise.draft || "_needs a basis in the brief_"}`, ...sf.promise.basis.map((c) => `  - basis: ${cite(c)}`), "");
  L.push("**Pain:**", list(sf.pain.map(cite)), "");
  L.push(`**Proof:** ${sf.proof.status.replace(/_/g, " ")}. ${sf.proof.rule}`, "Allowed kinds:", list(sf.proof.allowed_kinds), "");
  if (sf.proof.items.length) L.push("Verified facts the page may cite (these are not testimonials):", list(sf.proof.items.map(cite)), "");
  L.push("**Plan:**", ...sf.plan.map((s, i) => `${i + 1}. ${s}`), "");
  L.push(`**Picture (draft):** ${sf.picture.draft || "_needs a basis in the brief_"}`, "");
  L.push(`**Call to action:** ${sf.cta.label}`, "");
  L.push("**Objections to answer on the page:**", list(sf.objections.map((o) => cite(o.claim))), "");
  if (sf.customer_language.length) L.push("**Customer language:**", list(sf.customer_language.map((p) => `“${p}”`)), "");

  L.push("## Brand", "", "Direction from the brief:", list(bp.brand.direction.map(cite)), "", "Requirements:", list(bp.brand.requirements), "", bp.brand.asset_rights_policy, "");

  L.push("## Page map", "", "| Path | Purpose | Template | Launch | Gates |", "|---|---|---|---|---|");
  for (const p of bp.page_map) L.push(`| \`${p.path}\` | ${esc(p.purpose)} | ${p.template} | ${p.required_for_launch ? "required" : "later"} | ${p.gates.join(", ")} |`);
  L.push("");

  L.push("## Channel plan", "", "| Channel | Fit | Priority | Owner | Integration | Owner approval |", "|---|---|---|---|---|---|");
  for (const c of bp.channel_plan) L.push(`| ${esc(c.channel)} | ${c.fit} | ${c.priority.replace("_", " ")} | ${esc(c.owner_role)} | ${c.integration_required ?? "—"} | ${c.owner_approval_required ? "yes" : "no"} |`);
  L.push("");

  L.push("## Integrations", "", "| Service | Purpose | Status | Owner approval | Shared component |", "|---|---|---|---|---|");
  for (const i of bp.integrations) L.push(`| ${i.service} | ${esc(i.purpose)} | ${i.status} | ${i.owner_approval_required ? "yes" : "no"} | ${i.shared_component ?? "—"} |`);
  L.push("");

  L.push("## Measurement", "", `Ledger vertical \`${bp.measurement.ledger_vertical}\`, beacon prefix \`${bp.measurement.beacon_path_prefix}\`. Targets are set by the owner; none are invented here.`, "");
  L.push(list(bp.measurement.kpis.map((k) => `${k.label} (${k.unit}): ${k.target ?? "no target"} · ${k.state}`)), "");
  L.push("Falsifying tests:", list(bp.measurement.falsifying_tests), "");

  L.push("## Economics", "", bp.economics.note, "");
  if (bp.economics.scenarios) {
    L.push("| Scenario | Orders/mo | AOV | Gross/mo | Evidence |", "|---|---|---|---|---|");
    for (const [k, v] of Object.entries(bp.economics.scenarios)) {
      const s = v as Record<string, unknown>;
      L.push(`| ${k} | ${s.monthly_orders ?? "?"} | ${s.average_order_value ?? "?"} | ${s.monthly_gross ?? "?"} | ${s.evidence ?? "?"} |`);
    }
    L.push("");
  }

  L.push("## Budget and permissions", "", `Budget ceiling: ${bp.budget.ceiling_cents == null ? "not set (owner to set)" : `$${(bp.budget.ceiling_cents / 100).toFixed(2)}`}. Spend authorized: no. A ceiling is a limit, not permission to buy.`, "");
  L.push("Allowed without asking:", list(bp.permissions.allowed), "", "Needs the owner's approval:", list(bp.permissions.requires_owner_approval), "", "Never:", list(bp.permissions.prohibited), "");

  L.push("## Build stages", "");
  for (const s of bp.stages) {
    L.push(`### ${s.stage.replace("_", " ")}`, "", s.goal, "", `Depends on: ${s.depends_on.join(", ") || "—"} · Gates: ${s.gates.join(", ")}`, "");
    L.push(list(s.tasks.map((t) => `${t.title} _(${t.role}, ${t.kind})_`)), "");
    if (s.owner_approvals.length) L.push("Owner approvals:", list(s.owner_approvals), "");
  }

  L.push("## Done criteria", "", list(bp.done_criteria), "");
  L.push(`## Unknowns (${bp.unknowns.length})`, "", "| Field | What is missing | Resolve by |", "|---|---|---|", ...bp.unknowns.map((u) => `| \`${u.field}\` | ${esc(u.statement)} | ${esc(u.resolve_by)} |`), "");
  L.push("## Changelog", "", list(bp.changelog.map((c) => `${c.version} (${c.date}): ${c.change}`)), "");
  return L.join("\n");
}
