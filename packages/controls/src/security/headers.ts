/**
 * Security headers (gate G12 / audit S7: "no _headers in production").
 *
 * Two outputs:
 *  - apiSecurityHeaders(): headers for the FORGE API Worker (JSON only, never framed, never cached).
 *  - pagesHeadersFile():   a Cloudflare Pages `_headers` file for a niche site, with a CSP built from the
 *    third parties that site actually uses and sha256 hashes of its inline scripts (no 'unsafe-inline').
 * auditHeaders() checks a real response's headers against the policy (used by probes and QA).
 */
import { createHash } from "node:crypto";

export function apiSecurityHeaders(): Record<string, string> {
  return {
    "strict-transport-security": "max-age=31536000; includeSubDomains",
    "content-security-policy": "default-src 'none'; frame-ancestors 'none'; base-uri 'none'; form-action 'none'",
    "x-content-type-options": "nosniff",
    "x-frame-options": "DENY",
    "referrer-policy": "no-referrer",
    "cross-origin-opener-policy": "same-origin",
    "cross-origin-resource-policy": "same-origin",
    "permissions-policy": "camera=(), microphone=(), geolocation=(), payment=(), usb=()",
    "cache-control": "no-store",
  };
}

/** Framework-agnostic middleware: works with Hono (`app.use("*", secureHeaders())`) or any (c, next) shape exposing c.res.headers. */
export function secureHeaders(extra: Record<string, string> = {}) {
  const h = { ...apiSecurityHeaders(), ...extra };
  return async (c: { res: { headers: Headers } }, next: () => Promise<void>) => {
    await next();
    for (const [k, v] of Object.entries(h)) if (!c.res.headers.has(k)) c.res.headers.set(k, v);
  };
}

/** Third parties a site may load. Each adds only the origins that feature needs. */
export const THIRD_PARTIES = {
  cloudflareAnalytics: { script: ["https://static.cloudflareinsights.com"], connect: ["https://cloudflareinsights.com"] },
  lemonSqueezy: { script: ["https://assets.lemonsqueezy.com", "https://app.lemonsqueezy.com"], frame: ["https://*.lemonsqueezy.com"], connect: ["https://*.lemonsqueezy.com"], img: ["https://*.lemonsqueezy.com"] },
  mailerLite: { script: ["https://assets.mailerlite.com", "https://groot.mailerlite.com"], connect: ["https://assets.mailerlite.com", "https://connect.mailerlite.com", "https://groot.mailerlite.com"], style: ["https://assets.mlcdn.com"], img: ["https://*.mlcdn.com"], form: ["https://assets.mailerlite.com"] },
  googleFonts: { style: ["https://fonts.googleapis.com"], font: ["https://fonts.gstatic.com"] },
  pinterestTag: { script: ["https://s.pinimg.com"], img: ["https://ct.pinterest.com"], connect: ["https://ct.pinterest.com"] },
} as const;
export type ThirdParty = keyof typeof THIRD_PARTIES;

export interface SiteHeaderConfig {
  site: string;
  beaconOrigin: string;              // the sales/metrics Worker origin the site posts events to
  thirdParties: ThirdParty[];
  inlineScriptHashes?: string[];     // 'sha256-…' values from inlineScriptHashes()
  inlineStyles?: boolean;            // allow inline style attributes (common in hand-written sites); scripts stay strict
  embedPaths?: string[];             // paths other sites may iframe (e.g. calculator embeds) → frame-ancestors *
  reportOnly?: boolean;              // ship CSP as Report-Only for a first preview pass
}

const uniq = (xs: readonly string[]) => [...new Set(xs)];

export function siteCsp(cfg: SiteHeaderConfig, frameAncestors = "'none'"): string {
  const pick = (k: "script" | "connect" | "frame" | "img" | "style" | "font" | "form") =>
    uniq(cfg.thirdParties.flatMap((t) => ((THIRD_PARTIES[t] as Record<string, readonly string[]>)[k] ?? [])));
  const d: [string, string[]][] = [
    ["default-src", ["'self'"]],
    ["script-src", ["'self'", ...(cfg.inlineScriptHashes ?? []).map((h) => `'${h}'`), ...pick("script")]],
    ["style-src", ["'self'", ...(cfg.inlineStyles ? ["'unsafe-inline'"] : []), ...pick("style")]],
    ["img-src", ["'self'", "data:", ...pick("img")]],
    ["font-src", ["'self'", ...pick("font")]],
    ["connect-src", ["'self'", cfg.beaconOrigin, ...pick("connect")]],
    ["frame-src", pick("frame").length ? pick("frame") : ["'none'"]],
    ["form-action", ["'self'", ...pick("form")]],
    ["object-src", ["'none'"]],
    ["base-uri", ["'self'"]],
    ["frame-ancestors", [frameAncestors]],
    ["upgrade-insecure-requests", []],
  ];
  return d.map(([k, v]) => (v.length ? `${k} ${v.join(" ")}` : k)).join("; ");
}

/** Cloudflare Pages `_headers` text. Most specific rules last is NOT how Pages works: all matching blocks apply, so embed paths override with explicit values. */
export function pagesHeadersFile(cfg: SiteHeaderConfig): string {
  const cspName = cfg.reportOnly ? "Content-Security-Policy-Report-Only" : "Content-Security-Policy";
  const base = [
    `# Generated by @forge/controls pagesHeadersFile() for ${cfg.site}. Review in a Pages preview before production.`,
    "/*",
    "  Strict-Transport-Security: max-age=31536000; includeSubDomains",
    "  X-Content-Type-Options: nosniff",
    "  Referrer-Policy: strict-origin-when-cross-origin",
    "  Permissions-Policy: camera=(), microphone=(), geolocation=(), usb=()",
    "  Cross-Origin-Opener-Policy: same-origin-allow-popups",
    "  X-Frame-Options: DENY",
    `  ${cspName}: ${siteCsp(cfg)}`,
  ];
  for (const p of cfg.embedPaths ?? []) {
    base.push("", p, "  ! X-Frame-Options", `  ! ${cspName}`, `  ${cspName}: ${siteCsp(cfg, "*")}`);
  }
  const tooLong = base.find((l) => l.length > PAGES_HEADER_LINE_LIMIT);
  if (tooLong) throw new Error(`_headers line is ${tooLong.length} characters; Cloudflare Pages allows ${PAGES_HEADER_LINE_LIMIT}. Move inline scripts to files to reduce hashes.`);
  return base.join("\n") + "\n";
}
/** Cloudflare Pages limit per header line (docs: "Headers" limits). */
export const PAGES_HEADER_LINE_LIMIT = 2000;

/** sha256 CSP hashes for every inline <script> (no src) in an HTML document. */
export function inlineScriptHashes(html: string): string[] {
  const out: string[] = [];
  const re = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
  for (let m; (m = re.exec(html)); ) {
    const attrs = m[1] ?? ""; const body = m[2] ?? "";
    if (/\bsrc\s*=/.test(attrs) || /type\s*=\s*["']?application\/(ld\+)?json/i.test(attrs) || !body.trim()) continue;
    out.push(`sha256-${createHash("sha256").update(body, "utf8").digest("base64")}`);
  }
  return uniq(out);
}

/** Inline event handlers (onclick=…) cannot be hashed under CSP level 2; list them so the site owner can move them to JS. */
export function inlineHandlers(html: string): string[] {
  return uniq([...html.matchAll(/\s(on[a-z]+)\s*=\s*["']/gi)].map((m) => m[1]!.toLowerCase()));
}

export interface HeaderAudit { ok: boolean; missing: string[]; weak: string[] }
export function auditHeaders(headers: Headers | Record<string, string>, kind: "api" | "site"): HeaderAudit {
  const get = (k: string) => headers instanceof Headers ? headers.get(k) : Object.entries(headers).find(([h]) => h.toLowerCase() === k)?.[1] ?? null;
  const missing: string[] = []; const weak: string[] = [];
  const need = ["strict-transport-security", "x-content-type-options", "referrer-policy"];
  for (const k of need) if (!get(k)) missing.push(k);
  const csp = get("content-security-policy");
  if (!csp) missing.push("content-security-policy");
  else {
    if (/script-src[^;]*'unsafe-inline'/.test(csp) && !/script-src[^;]*'(sha256|nonce)-/.test(csp)) weak.push("script-src allows 'unsafe-inline'");
    const scriptSrc = /(?:^|;)\s*script-src([^;]*)/.exec(csp)?.[1] ?? /(?:^|;)\s*default-src([^;]*)/.exec(csp)?.[1] ?? "";
    if (/(^|\s)\*(\s|$)/.test(scriptSrc)) weak.push("script-src allows any origin");
    if (/(^|\s)(https?:|data:|blob:)(\s|$)/.test(scriptSrc)) weak.push("script-src allows a whole scheme");
    if (/'unsafe-eval'/.test(scriptSrc)) weak.push("script-src allows 'unsafe-eval'");
    if (/(?:^|;)\s*default-src[^;]*(\s|^)\*(\s|;|$)/.test(csp)) weak.push("default-src allows any origin");
    if (!/frame-ancestors/.test(csp) && !get("x-frame-options")) weak.push("no framing rule");
    if (kind === "api" && !/default-src 'none'/.test(csp)) weak.push("API CSP should be default-src 'none'");
  }
  const hsts = get("strict-transport-security");
  if (hsts && Number(/max-age=(\d+)/.exec(hsts)?.[1] ?? 0) < 15552000) weak.push("HSTS max-age under 180 days");
  if (get("x-content-type-options") && get("x-content-type-options")!.toLowerCase() !== "nosniff") weak.push("x-content-type-options not nosniff");
  if (kind === "api" && get("access-control-allow-origin") === "*") weak.push("API allows any origin");
  return { ok: !missing.length && !weak.length, missing, weak };
}
